"""Plausible capture locations drawn from the IANA tz database.

``zone1970.tab`` gives one principal location per canonical time zone
(~300 cities, public domain).  A GPS fix is a random point in a disk
around one of them, rejected when it falls in water.  The data blob
(``zones.bin``) is generated by ``tools/make_geo_data.py``: it carries
the coordinates, a 0.5 km land bitmap for the 25 km disk and a city
elevation, so encodes stay offline and reproducible.

Sampling pulls the radius in when a disk is mostly water, so coastal
cities still get land points instead of drifting offshore; narrow atolls
the 1 km source mask cannot resolve are dropped from the table at build
time.
"""
from __future__ import annotations

import datetime as _dt
import math
import random
import struct
import zlib
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from zoneinfo import ZoneInfo, ZoneInfoNotFoundError

#: The land grid covers a disk of this radius around each zone centre.
MAX_RADIUS_KM = 25.0
#: Land bitmap resolution inside that disk.
CELL_KM = 0.5
GRID = int(round(2 * MAX_RADIUS_KM / CELL_KM))
MASK_BYTES = (GRID * GRID + 7) // 8
MAGIC = b"STGEO1"
KM_PER_DEG = 111.32
_SHRINK = 0.55
_TRIES = 14


@dataclass(frozen=True)
class Zone:
    """One principal tz location and the land around it."""

    name: str
    lat: float
    lon: float
    elevation_m: int
    mask: bytes

    def cell_is_land(self, i: int, j: int) -> bool:
        """Whether grid cell ``(i, j)`` (x, y) is land."""
        if not 0 <= i < GRID or not 0 <= j < GRID:
            return False
        bit = j * GRID + i
        return bool(self.mask[bit >> 3] & (1 << (bit & 7)))

    def cell_of(self, lat: float, lon: float) -> tuple[int, int]:
        """Grid cell holding a point near this zone (for checks/tests)."""
        y = (lat - self.lat) * KM_PER_DEG
        coslat = max(0.05, math.cos(math.radians(self.lat)))
        x = _wrap_lon(lon - self.lon) * KM_PER_DEG * coslat
        i = min(GRID - 1, max(0, int((x + MAX_RADIUS_KM) / CELL_KM)))
        j = min(GRID - 1, max(0, int((y + MAX_RADIUS_KM) / CELL_KM)))
        return i, j

    def point_is_land(self, lat: float, lon: float) -> bool:
        return self.cell_is_land(*self.cell_of(lat, lon))

    def offset_at(self, local_time: _dt.datetime) -> _dt.timedelta:
        return offset_delta(self.name, local_time)

    def offset_string(self, local_time: _dt.datetime) -> str:
        return format_offset(self.offset_at(local_time))


@dataclass(frozen=True)
class Location:
    """A sampled capture point, altitude already drawn."""

    zone: str
    lat: float
    lon: float
    altitude_m: float

    def offset_at(self, local_time: _dt.datetime) -> _dt.timedelta:
        return offset_delta(self.zone, local_time)

    def offset_string(self, local_time: _dt.datetime) -> str:
        return format_offset(self.offset_at(local_time))


def _wrap_lon(lon: float) -> float:
    return (lon + 180.0) % 360.0 - 180.0


@lru_cache(maxsize=None)
def _zone(name: str) -> ZoneInfo:
    return ZoneInfo(name)


def offset_delta(zone_name: str, local_time: _dt.datetime) -> _dt.timedelta:
    """UTC offset of ``zone_name`` at the given local wall time."""
    try:
        return _zone(zone_name).utcoffset(local_time) or _dt.timedelta(0)
    except ZoneInfoNotFoundError as exc:  # no system tzdata and no tzdata wheel
        raise RuntimeError(
            "time zone data unavailable; install the 'tzdata' package "
            f"to resolve {zone_name!r}") from exc


def format_offset(delta: _dt.timedelta) -> str:
    """``±HH:MM`` as written to the EXIF OffsetTime* tags."""
    seconds = int(delta.total_seconds())
    sign = "+" if seconds >= 0 else "-"
    minutes = abs(seconds) // 60
    return f"{sign}{minutes // 60:02d}:{minutes % 60:02d}"


@lru_cache(maxsize=1)
def zones() -> tuple[Zone, ...]:
    """The vendored principal locations (loaded once, ~2 ms)."""
    path = Path(__file__).with_name("zones.bin")
    try:
        blob = zlib.decompress(path.read_bytes())
    except OSError as exc:  # pragma: no cover - broken install
        raise RuntimeError(f"missing location data: {path}") from exc
    if not blob.startswith(MAGIC):
        raise RuntimeError(f"bad location data header in {path}")
    count = struct.unpack_from("<H", blob, len(MAGIC))[0]
    pos = len(MAGIC) + 2
    out: list[Zone] = []
    for _ in range(count):
        length = blob[pos]
        pos += 1
        name = blob[pos:pos + length].decode("utf-8")
        pos += length
        lat, lon, mask_len, elevation = struct.unpack_from(
            "<iiHh", blob, pos)
        pos += 12
        mask = blob[pos:pos + mask_len]
        pos += mask_len
        if mask_len != MASK_BYTES:
            raise RuntimeError(
                f"bad land mask for {name}: {mask_len} bytes")
        out.append(Zone(name, lat / 1_000_000, lon / 1_000_000,
                        elevation, mask))
    if not out:
        raise RuntimeError(f"no locations in {path}")
    if pos != len(blob):
        raise RuntimeError(
            f"truncated location data in {path}: {pos} of {len(blob)} bytes")
    return tuple(out)


def validate_radius(radius_km: float) -> float:
    """Reject radii the land grid cannot cover."""
    try:
        radius = float(radius_km)
    except (TypeError, ValueError) as exc:
        raise ValueError(
            f"gps radius must be a number between 0 and "
            f"{MAX_RADIUS_KM:g} km (got {radius_km!r})") from exc
    if not math.isfinite(radius) or radius <= 0 or radius > MAX_RADIUS_KM:
        raise ValueError(
            f"gps radius must be between 0 and {MAX_RADIUS_KM:g} km "
            f"(got {radius_km!r}); the offline land grid covers 25 km")
    return radius


def _candidates(local_time: _dt.datetime | None,
                offset: str | None) -> tuple[Zone, ...]:
    table = zones()
    if offset is None:
        return table
    if local_time is None:
        raise ValueError("local_time is required when filtering by offset")
    matching = tuple(z for z in table if z.offset_string(local_time) == offset)
    # A pinned time can carry an offset no zone uses (e.g. an odd system
    # offset); fall back to the whole table rather than failing.
    return matching or table


@lru_cache(maxsize=64)
def _nearest_land_cell(zone: Zone) -> tuple[int, int] | None:
    """Closest land cell to the centre (narrow-atoll fallback)."""
    best: tuple[float, int, int] | None = None
    for j in range(GRID):
        y = (j + 0.5) * CELL_KM - MAX_RADIUS_KM
        for i in range(GRID):
            if not zone.cell_is_land(i, j):
                continue
            x = (i + 0.5) * CELL_KM - MAX_RADIUS_KM
            distance = math.hypot(x, y)
            if best is None or distance < best[0]:
                best = (distance, i, j)
    if best is None:
        return None
    return best[1], best[2]


def sample_location(rng: random.Random, radius_km: float = MAX_RADIUS_KM,
                    *, local_time: _dt.datetime | None = None,
                    offset: str | None = None,
                    zone: str | None = None) -> Location:
    """Pick a random point within ``radius_km`` of a principal location.

    Points are uniform by area and land-only: a candidate over water
    pulls the radius in (so coastal cities stay on the coast instead of
    spreading into the sea), then snaps to the nearest land cell when
    even that fails, which can exceed a very small ``radius_km`` on
    narrow atolls.  ``offset`` restricts the zone pool to ones whose UTC
    offset at ``local_time`` matches, which keeps a pinned capture time
    consistent with the coordinates; ``zone`` forces one zone (tests).
    """
    radius = validate_radius(radius_km)
    table = zones()
    if zone is not None:
        candidates = tuple(z for z in table if z.name == zone)
        if not candidates:
            raise ValueError(f"unknown location zone {zone!r}")
    else:
        candidates = _candidates(local_time, offset)
    chosen = rng.choice(candidates)

    span = MAX_RADIUS_KM
    r = radius
    x = y = 0.0
    for _ in range(_TRIES):
        distance = r * math.sqrt(rng.random())
        theta = rng.uniform(0.0, 2.0 * math.pi)
        x = distance * math.cos(theta)
        y = distance * math.sin(theta)
        i = min(GRID - 1, max(0, int((x + span) / CELL_KM)))
        j = min(GRID - 1, max(0, int((y + span) / CELL_KM)))
        if chosen.cell_is_land(i, j):
            break
        r *= _SHRINK
    else:
        cell = _nearest_land_cell(chosen)
        if cell is None:
            x = y = 0.0
        else:
            i, j = cell
            x = (i + 0.5) * CELL_KM - span + rng.uniform(-0.2, 0.2)
            y = (j + 0.5) * CELL_KM - span + rng.uniform(-0.2, 0.2)

    coslat = max(0.05, math.cos(math.radians(chosen.lat)))
    lat = chosen.lat + y / KM_PER_DEG
    lon = _wrap_lon(chosen.lon + x / (KM_PER_DEG * coslat))
    # Phone GPS altitude follows the local terrain (~20 m of noise), and
    # it is part of the shared fix for split sets.
    altitude = chosen.elevation_m + rng.uniform(-20.0, 20.0)
    return Location(chosen.name, lat, lon, altitude)
